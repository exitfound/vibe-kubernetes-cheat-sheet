// ── Last-changed dates ───────────────────────────────────────────────────────────────────────────
// True dates without git history (CI clones one commit deep): per page a content hash and the day it
// moved (today), a new page seeded from its source's last commit. --check fails while it is behind.
const DATES_FILE = 'tools/pages/dates.json';
const git = (...args) => { try { return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim(); } catch { return ''; } };
async function dateMap(rev) {
  const old = existsSync(join(ROOT, DATES_FILE)) ? JSON.parse(await readFile(join(ROOT, DATES_FILE), 'utf8')) : {};
  const today = new Date().toISOString().slice(0, 10);
  const seed = (file) => (git('status', '--porcelain', '--', file) ? today : git('log', '-1', '--format=%cs', '--', file) || today);
  const out = {};
  const date = (key, hash, file) => {
    out[key] = old[key]?.rev === hash ? old[key] : { rev: hash, date: old[key] ? today : seed(file) };
  };
  // The page shows the desc that REV leaves out, so a reworded desc still moves its <lastmod>.
  const page = (s) => createHash('sha1').update(rev[s.id] + s.desc).digest('hex').slice(0, 8);
  for (const s of DIAGRAMS) date(s.id, page(s), `diagrams/js/diagrams/${s.category}/${s.id}.js`);
  for (const sec of SECTIONS) date(`cli:${sec.id}`, createHash('sha1').update(JSON.stringify(sec)).digest('hex').slice(0, 8), 'cli/js/data.js');
  return out;
}
const datesFile = (d) => `{\n${Object.keys(d).sort().map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(d[k])}`).join(',\n')}\n}\n`;

// ── Card revisions ───────────────────────────────────────────────────────────────────────────────
// A function's source with its comments dropped and the whitespace between tokens collapsed to one
// space. String, template and regex literals pass through untouched, so a `//` inside one survives.
function codeOnly(src) {
  let out = '', i = 0, gap = false;
  const holes = []; // brace depth inside each open template `${`
  const literal = (q, j) => { while (j < src.length && src[j] !== q) j += src[j] === '\\' ? 2 : 1; return j + 1; };
  const template = (j) => { // from just after a backtick or a closing `}`, to past the end or the next `${`
    while (j < src.length && src[j] !== '`' && !(src[j] === '$' && src[j + 1] === '{')) j += src[j] === '\\' ? 2 : 1;
    if (src[j] === '$') { holes.push(0); return j + 2; }
    return j + 1;
  };
  while (i < src.length) {
    const c = src[i], d = src[i + 1];
    if (c === '/' && d === '/') { const j = src.indexOf('\n', i); i = j < 0 ? src.length : j; gap = true; continue; }
    if (c === '/' && d === '*') { const j = src.indexOf('*/', i + 2); i = j < 0 ? src.length : j + 2; gap = true; continue; }
    if (/\s/.test(c)) { gap = true; i++; continue; }
    if (gap && out) out += ' ';
    gap = false;
    let j = i + 1;
    if (c === '\'' || c === '"') j = literal(c, j);
    else if (c === '`') j = template(j);
    else if (c === '{' && holes.length) holes[holes.length - 1]++;
    else if (c === '}' && holes.length && holes[holes.length - 1]-- === 0) { holes.pop(); j = template(j); }
    else if (c === '/' && /^$|[(,=:[!&|?{};]$/.test(out.trimEnd().slice(-1))) {
      let cls = false; // a regex literal: up to the closing slash outside a [class], then its flags
      while (j < src.length && (src[j] !== '/' || cls)) { if (src[j] === '[') cls = true; else if (src[j] === ']') cls = false; j += src[j] === '\\' ? 2 : 1; }
      j++;
      while (/[a-z]/.test(src[j] || '')) j++;
    }
    out += src.slice(i, j);
    i = j;
  }
  return out;
}

// NEW again after any change to a card's entry but its desc, poster, scene or steps, function bodies
// through codeOnly so comments do not count. Kit and lib/ changes would mark every card and are left
// out: the kit pulses a ball bakes into F.pulse hash as their name.
async function cardRevisions() {
  const rev = {};
  for (const s of DIAGRAMS) {
    const m = await from(`diagrams/js/diagrams/${s.category}/${s.id}.js`);
    const kit = await from(`diagrams/js/diagrams/${s.category}/${s.category}-kit.js`);
    const { desc, ...entry } = s; // a reworded desc is not new content: the steps carry it
    const body = JSON.stringify({ entry, poster: POSTERS[s.id] ?? null, scene: m.SCENE, steps: m.STEPS_SPEC },
      (k, v) => (v === kit.pulsePod ? 'kit:pulsePod' : v === kit.pulsePodDim ? 'kit:pulsePodDim'
        : typeof v === 'function' ? codeOnly(v.toString()) : v));
    rev[s.id] = createHash('sha1').update(body).digest('hex').slice(0, 8);
  }
  return rev;
}
