// The poster as a standalone image file beside the page, so the diagram can be indexed and shared:
// the same drawing on its own dark ground, named by the scene's own description.
const POSTER_OPEN = '<svg viewBox="0 0 320 180" preserveAspectRatio="xMidYMid meet" aria-hidden="true">';
function diagramFile(s, alt) {
  const svg = renderPoster(s).trim();
  // A missed replace would ship a file with no xmlns, which no browser draws as an image.
  if (!svg.startsWith(POSTER_OPEN)) throw new Error(`build.mjs: the poster of ${s.id} no longer opens with the tag diagramFile rewrites`);
  return svg.replace(POSTER_OPEN,
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 180" width="1280" height="720" role="img"><title>${esc(alt)}</title>\n      <rect width="320" height="180" fill="#0e0a1f"/>`) + '\n';
}

