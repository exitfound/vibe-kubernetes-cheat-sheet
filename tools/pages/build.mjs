for (const [i, s] of schemeOrder.entries()) want.set(`${CARD_DIR}/${s.id}/index.html`, await schemePage(s, i));
want.set(`${CARD_DIR}/index.html`, schemeIndexPage());
for (const [i, s] of SECTIONS.entries()) want.set(`${SECTION_DIR}/${s.id}/index.html`, cliPage(s, i));
want.set(`${SECTION_DIR}/index.html`, sectionIndexPage());
want.set('sitemap.xml', sitemap());

// A stale generated page: a directory whose index.html carries MARK and is not in `want`, including
// one straight under scheme/ or cli/ (the old location). Nothing without MARK is ever touched.
const stale = [];
for (const app of ['scheme', 'cli', CARD_DIR, SECTION_DIR]) {
  if (!existsSync(join(ROOT, app))) continue;
  for (const d of await readdir(join(ROOT, app), { withFileTypes: true })) {
    if (!d.isDirectory()) continue;
    const rel = `${app}/${d.name}/index.html`;
    if (want.has(rel) || !existsSync(join(ROOT, rel))) continue;
    if ((await readFile(join(ROOT, rel), 'utf8')).includes(MARK)) stale.push(`${app}/${d.name}`);
  }
}

const changed = [];
for (const [rel, html] of want) {
  const file = join(ROOT, rel);
  const cur = existsSync(file) ? await readFile(file, 'utf8') : null;
  if (cur === html) continue;
  changed.push(rel);
  if (!CHECK) {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, html);
  }
}
if (!CHECK) for (const dir of stale) await rm(join(ROOT, dir), { recursive: true });

if (CHECK) {
  if (changed.length || stale.length) {
    console.error(`pages are out of date: ${changed.length} to write, ${stale.length} to delete. Run: node tools/pages/build.mjs`);
    for (const f of [...changed, ...stale].slice(0, 20)) console.error(`  ${f}`);
    process.exit(1);
  }
  console.log(`pages up to date: ${want.size - 1} pages + sitemap.xml`);
} else {
  console.log(`wrote ${changed.length} file(s), deleted ${stale.length} stale page(s); ${want.size - 1} pages + sitemap.xml in total`);
}
