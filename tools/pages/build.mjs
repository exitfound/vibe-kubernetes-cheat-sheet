// A <title> Google shows whole: the most telling form that fits in 60 characters.
const fitTitle = (...forms) => forms.find(f => f.length <= 60) || forms[forms.length - 1];

const esc = (s) => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const jsonLd = (o) => JSON.stringify(o).replace(/</g, '\\u003c');

// A meta description: the first whole sentences that fit in 160 characters. A sentence ends at . ! or ?
// before a space and a capital, so `resolv.conf` or `127.0.0.1` never split. Under 100 characters it
// is too thin, and the text is cut at a word near 160 instead.
function summary(text, max = 160) {
  const parts = [];
  let from = 0;
  for (const m of text.matchAll(/[.!?](?=\s+[A-Z0-9"'(`]|\s*$)/g)) {
    parts.push(text.slice(from, m.index + 1).trim());
    from = m.index + 1;
  }
  if (text.slice(from).trim()) parts.push(text.slice(from).trim());
  let out = '';
  for (const p of parts) {
    const next = out ? `${out} ${p}` : p;
    if (next.length > max) break;
    out = next;
  }
  if (out.length >= 100) return out;
  return text.length <= max ? text : text.slice(0, max - 3).replace(/\s+\S*$/, '') + '...';
}

// ── Shared chrome, read out of the live pages so the static ones match them ──────────────────────
const schemeIndex = await readFile(join(ROOT, 'scheme/index.html'), 'utf8');
const cliIndex = await readFile(join(ROOT, 'cli/index.html'), 'utf8');
const pick = (html, re, what) => {
  const m = html.match(re);
  if (!m) throw new Error(`build.mjs: could not find ${what} in a live page, the template moved`);
  return m[0];
};
const FONTS = pick(schemeIndex, /  <link rel="preconnect" href="https:\/\/fonts\.googleapis\.com">[\s\S]*?<\/noscript>/, 'the font links');
const BEACON = pick(schemeIndex, /<script defer src="https:\/\/static\.cloudflareinsights\.com[^\n]*<\/script>/, 'the analytics beacon');
// The static pages have no shortcuts sheet, so the sidebar keyboard button goes.
const sidebar = (html) => pick(html, /  <aside class="sidebar"[\s\S]*?<\/aside>\s*<button class="side-expand"[\s\S]*?<\/button>/, 'the sidebar')
  .replace(/\s*<button class="side-btn side-keys"[\s\S]*?<\/button>/, '');
const logo = (html) => pick(html, /      <a class="logo" href="\/"[\s\S]*?\n      <\/a>/, 'the logo');

