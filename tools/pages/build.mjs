// ── Command section pages ────────────────────────────────────────────────────────────────────────
// The /cli/ category of a section, by its `sub` label. app.js keeps the same map as CATEGORIES.
const CLI_CAT = {
  Installation: ['installation', 'kubernetes'],
  Cluster: ['cluster', 'kubernetes'],
  Workloads: ['workloads', 'kubernetes'],
  Helm: ['helm', 'tools'],
  Kustomize: ['kustomize', 'tools'],
  K9s: ['k9s', 'tools'],
  'Debug K8s': ['troubleshooting-kubernetes', 'troubleshooting'],
  'Debug Tools': ['troubleshooting-tools', 'troubleshooting'],
};
// The words a search for these commands would use: `kubectl Pods`, `Helm Releases`, `Kubeadm`.
function cliHeading(sec) {
  switch (sec.sub) {
    case 'Installation': return `${sec.title} commands`;
    case 'Cluster':
    case 'Workloads': return `kubectl ${sec.title} commands`;
    // "K9s UI Shortcuts" is a list of keys, not of commands.
    case 'Helm': case 'Kustomize': case 'K9s': return /shortcuts/i.test(sec.title) ? `${sec.sub} ${sec.title}` : `${sec.sub} ${sec.title} commands`;
    case 'Debug K8s': return `Debug Kubernetes ${sec.title}: troubleshooting commands`;
    case 'Debug Tools': return `Debug ${sec.title}: troubleshooting commands`;
    default: return `${sec.title} commands`;
  }
}

const COPY_SCRIPT = `
    // Copy on a click anywhere on a command, as on /cli/.
    const COPY = ${JSON.stringify(COPY_ICON)}, CHECK = ${JSON.stringify(CHECK_ICON)};
    // The section index (/cli/section/) has no commands, so the handler is attached only where they are.
    document.querySelector('.page-cli')?.addEventListener('click', (e) => {
      const item = e.target.closest('.cmd-item');
      if (!item) return;
      const btn = item.querySelector('.copy-btn');
      const done = () => {
        btn.innerHTML = CHECK; btn.classList.add('copied');
        setTimeout(() => { btn.innerHTML = COPY; btn.classList.remove('copied'); }, 1500);
      };
      if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(item.dataset.raw).then(done, () => {});
    });`;

