// ── Sitemap ──────────────────────────────────────────────────────────────────────────────────────
// No <lastmod>: it would have to come from git, and a date that changes on every commit would make
// --check fail right after any commit. Google reads lastmod only when it is consistently right.
function sitemap() {
  const urls = [
    [`${SITE}/`, '1.0'], [`${SITE}/cli/`, '0.9'], [`${SITE}/scheme/`, '0.9'],
    [`${SITE}/${CARD_DIR}/`, '0.8'], [`${SITE}/${SECTION_DIR}/`, '0.8'],
    ...schemeOrder.map(s => [`${SITE}${cardPath(s.id)}`, '0.7']),
    ...SECTIONS.map(s => [`${SITE}${sectionPath(s.id)}`, '0.7']),
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by tools/pages/build.mjs: edit the generator, not this file -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(([loc, pr]) => `  <url>
    <loc>${loc}</loc>
    <changefreq>weekly</changefreq>
    <priority>${pr}</priority>
  </url>`).join('\n')}
</urlset>
`;
}

