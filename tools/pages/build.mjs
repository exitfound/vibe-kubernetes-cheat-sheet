const breadcrumbLd = (items) => ({
  '@type': 'BreadcrumbList',
  itemListElement: items.map(([name, url], i) => ({ '@type': 'ListItem', position: i + 1, name, item: url })),
});

// ── Scheme card pages ────────────────────────────────────────────────────────────────────────────
// Grid order, the same walk app.js buildUnits() does: category, then subcategory, then catalog order.
const schemeOrder = [];
for (const c of CATEGORIES.filter(c => c.key !== 'all')) {
  const inCat = SCHEMES.filter(s => s.category === c.key);
  const subs = SUBCATEGORIES[c.key] || [];
  for (const sc of subs) schemeOrder.push(...inCat.filter(s => s.subcategory === sc.key));
  schemeOrder.push(...inCat.filter(s => !subs.some(sc => sc.key === s.subcategory)));
}

